-- Ejecutar SOLO tras validar diagnostico_cxp_cuenta_usuario.sql y confirmar
-- que SEG_USUARIOS/USUARIO y sus PK coinciden con el DDL previsto.
-- No crea usuarios ni asigna identidades automáticamente.
CREATE TABLE CXP_CUENTA_USUARIO (
  SEG_ID_USUARIO NUMBER NOT NULL,
  USU_ID_USUARIO NUMBER NOT NULL,
  CONSTRAINT PK_CXP_CUENTA_USUARIO PRIMARY KEY (SEG_ID_USUARIO),
  CONSTRAINT UQ_CXP_CUENTA_USUARIO_OPERATIVO UNIQUE (USU_ID_USUARIO),
  CONSTRAINT FK_CXP_CUENTA_SEG FOREIGN KEY (SEG_ID_USUARIO)
    REFERENCES SEG_USUARIOS (ID_USUARIO),
  CONSTRAINT FK_CXP_CUENTA_USU FOREIGN KEY (USU_ID_USUARIO)
    REFERENCES USUARIO (USU_ID_USUARIO)
);
