-- ============================================================================
-- MIGRACION 001 - FACTURAS ESPECIALES Y TRIBUTOS (RF-06, RF-14, RF-15, RF-16)
-- Esquema: PROYECTOANALISIS | Responsable: CXP_DOCUMENTO / DETALLE / TRIBUTO
-- ============================================================================
-- Se ejecuta SOBRE una instalacion CXP existente (17 tablas, 102 FK).
-- Es re-ejecutable: cada paso comprueba si ya fue aplicado y no borra datos.
--
-- 1. CK_CXP_DOC_TIPO: agrega FACTURA_ESPECIAL conservando los 14 tipos actuales.
--    Primero se crea y valida la restriccion nueva y solo despues se retira la
--    anterior, de modo que la tabla nunca queda sin la restriccion.
-- 2. CXP_REGLA_TRIBUTARIA: reglas de IVA/ISR parametrizables, versionadas y con
--    vigencia. Una modificacion crea una version nueva; la anterior se conserva.
-- 3. CXP_DOCUMENTO_TRIBUTO.ID_REGLA_TRIBUTARIA: identifica la regla (version)
--    aplicada. Porcentaje, base y monto ya se guardan en la fila del tributo,
--    por lo que los cambios futuros de reglas no alteran documentos procesados.
-- 4. CXP_FACTURA_ESPECIAL: extension 1:1 de CXP_DOCUMENTO con los datos fiscales
--    del proveedor, la revision, la emision y la constancia numerada.
-- 5. Parametros: serie, correlativos sin huecos y aprobadores autorizados.
--
-- No crea triggers. Las reglas del flujo (revision, aprobacion, emision unica,
-- anulacion) se aplican en la capa de servicios dentro de transacciones.
-- Reversion: 001_facturas_especiales_tributos_rollback.sql
-- ============================================================================

SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

PROMPT 1. Ampliando CK_CXP_DOC_TIPO con FACTURA_ESPECIAL...
DECLARE
    V_CONDICION VARCHAR2(4000);
    V_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_N FROM USER_TABLES WHERE TABLE_NAME = 'CXP_DOCUMENTO';
    IF V_N = 0 THEN
        RAISE_APPLICATION_ERROR(-20301, 'No existe CXP_DOCUMENTO. Instalar primero el DDL de CXP.');
    END IF;

    SELECT MAX(SEARCH_CONDITION_VC) INTO V_CONDICION
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'CXP_DOCUMENTO' AND CONSTRAINT_NAME = 'CK_CXP_DOC_TIPO';

    IF V_CONDICION IS NOT NULL AND INSTR(V_CONDICION, 'FACTURA_ESPECIAL') > 0 THEN
        DBMS_OUTPUT.PUT_LINE('CK_CXP_DOC_TIPO ya admite FACTURA_ESPECIAL. Sin cambios.');
    ELSE
        -- Restriccion nueva con los tipos actuales + FACTURA_ESPECIAL (ENABLE VALIDATE).
        EXECUTE IMMEDIATE q'[
            ALTER TABLE CXP_DOCUMENTO ADD CONSTRAINT CK_CXP_DOC_TIPO_V2 CHECK
            (TIPO_DOCUMENTO IN ('FACTURA', 'FACTURA_CAMBIARIA', 'NOTA_CREDITO',
                                'NOTA_DEBITO', 'RECIBO', 'REEMBOLSO',
                                'LIQUIDACION_VIATICO', 'GASTO_CAJA_CHICA',
                                'CUOTA_CONTRATO', 'CUOTA_PRESTAMO',
                                'OBLIGACION_FISCAL', 'SALDO_INICIAL',
                                'COMPROBANTE_SERVICIO', 'OTRO',
                                'FACTURA_ESPECIAL')) ENABLE VALIDATE]';
        IF V_CONDICION IS NOT NULL THEN
            EXECUTE IMMEDIATE 'ALTER TABLE CXP_DOCUMENTO DROP CONSTRAINT CK_CXP_DOC_TIPO';
        END IF;
        EXECUTE IMMEDIATE 'ALTER TABLE CXP_DOCUMENTO RENAME CONSTRAINT CK_CXP_DOC_TIPO_V2 TO CK_CXP_DOC_TIPO';
        DBMS_OUTPUT.PUT_LINE('CK_CXP_DOC_TIPO actualizado.');
    END IF;
END;
