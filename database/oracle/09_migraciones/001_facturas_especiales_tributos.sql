PROMPT 2. Creando CXP_REGLA_TRIBUTARIA...
DECLARE
    V_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_N FROM USER_TABLES WHERE TABLE_NAME = 'CXP_REGLA_TRIBUTARIA';
    IF V_N > 0 THEN
        DBMS_OUTPUT.PUT_LINE('CXP_REGLA_TRIBUTARIA ya existe. Sin cambios.');
        RETURN;
    END IF;
    EXECUTE IMMEDIATE q'[
        CREATE TABLE CXP_REGLA_TRIBUTARIA (
            ID_REGLA_TRIBUTARIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            CODIGO_REGLA        VARCHAR2(30)   NOT NULL,
            VERSION_REGLA       NUMBER(6)      DEFAULT 1 NOT NULL,
            ID_REGLA_ANTERIOR   NUMBER,
            TIPO_DOCUMENTO      VARCHAR2(30)   DEFAULT 'FACTURA_ESPECIAL' NOT NULL,
            TIPO_TRIBUTO        VARCHAR2(15)   NOT NULL,
            CODIGO_TRIBUTO      VARCHAR2(30)   NOT NULL,
            NOMBRE_TRIBUTO      VARCHAR2(120)  NOT NULL,
            PORCENTAJE          NUMBER(9,6)    DEFAULT 0 NOT NULL,
            MONTO_FIJO          NUMBER(18,2)   DEFAULT 0 NOT NULL,
            BASE_DESDE          NUMBER(18,2)   DEFAULT 0 NOT NULL,
            BASE_HASTA          NUMBER(18,2),
            SOBRE_EXCEDENTE     CHAR(1)        DEFAULT 'N' NOT NULL,
            MONEDA              VARCHAR2(3),
            VIGENTE_DESDE       DATE           NOT NULL,
            VIGENTE_HASTA       DATE,
            ESTADO              VARCHAR2(20)   DEFAULT 'VIGENTE' NOT NULL,
            MOTIVO_CAMBIO       VARCHAR2(500),
            CREADA_POR          NUMBER         NOT NULL,
            FECHA_CREACION      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
            MODIFICADA_POR      NUMBER,
            FECHA_MODIFICACION  TIMESTAMP,
            CONSTRAINT PK_CXP_REGLA_TRIB PRIMARY KEY (ID_REGLA_TRIBUTARIA),
            CONSTRAINT UK_CXP_RTRIB_VERSION UNIQUE (CODIGO_REGLA, VERSION_REGLA),
            CONSTRAINT FK_CXP_RTRIB_ANT FOREIGN KEY (ID_REGLA_ANTERIOR)
                REFERENCES CXP_REGLA_TRIBUTARIA (ID_REGLA_TRIBUTARIA),
            CONSTRAINT FK_CXP_RTRIB_CREA FOREIGN KEY (CREADA_POR)
                REFERENCES USUARIO (USU_ID_USUARIO),
            CONSTRAINT FK_CXP_RTRIB_MOD FOREIGN KEY (MODIFICADA_POR)
                REFERENCES USUARIO (USU_ID_USUARIO),
            CONSTRAINT CK_CXP_RTRIB_TIPO CHECK (TIPO_TRIBUTO IN ('IMPUESTO', 'RETENCION')),
            CONSTRAINT CK_CXP_RTRIB_MONTOS CHECK
                (PORCENTAJE >= 0 AND PORCENTAJE <= 100 AND MONTO_FIJO >= 0 AND BASE_DESDE >= 0
                 AND (BASE_HASTA IS NULL OR BASE_HASTA >= BASE_DESDE)),
            CONSTRAINT CK_CXP_RTRIB_EXCED CHECK (SOBRE_EXCEDENTE IN ('S', 'N')),
            CONSTRAINT CK_CXP_RTRIB_MONEDA CHECK (MONEDA IS NULL OR LENGTH(MONEDA) = 3),
            CONSTRAINT CK_CXP_RTRIB_VIGENCIA CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA >= VIGENTE_DESDE),
            CONSTRAINT CK_CXP_RTRIB_ESTADO CHECK (ESTADO IN ('VIGENTE', 'REEMPLAZADA', 'FINALIZADA')),
            CONSTRAINT CK_CXP_RTRIB_VERSION CHECK (VERSION_REGLA > 0),
            CONSTRAINT CK_CXP_RTRIB_CAMBIO CHECK (VERSION_REGLA = 1 OR MOTIVO_CAMBIO IS NOT NULL)
        )]';
    EXECUTE IMMEDIATE q'[
        CREATE INDEX IX_CXP_RTRIB_APLICA ON CXP_REGLA_TRIBUTARIA
            (TIPO_DOCUMENTO, TIPO_TRIBUTO, CODIGO_TRIBUTO, VIGENTE_DESDE, VIGENTE_HASTA)]';
    DBMS_OUTPUT.PUT_LINE('CXP_REGLA_TRIBUTARIA creada.');
END;
