PROMPT 3. Vinculando CXP_DOCUMENTO_TRIBUTO con la regla aplicada...
DECLARE
    V_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_N FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'CXP_DOCUMENTO_TRIBUTO' AND COLUMN_NAME = 'ID_REGLA_TRIBUTARIA';
    IF V_N = 0 THEN
        -- Columna opcional: los tributos existentes (sin regla) no se modifican.
        EXECUTE IMMEDIATE 'ALTER TABLE CXP_DOCUMENTO_TRIBUTO ADD (ID_REGLA_TRIBUTARIA NUMBER)';
        EXECUTE IMMEDIATE q'[
            ALTER TABLE CXP_DOCUMENTO_TRIBUTO ADD CONSTRAINT FK_CXP_TRIB_REGLA
            FOREIGN KEY (ID_REGLA_TRIBUTARIA) REFERENCES CXP_REGLA_TRIBUTARIA (ID_REGLA_TRIBUTARIA)]';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_CXP_TRIB_REGLA ON CXP_DOCUMENTO_TRIBUTO (ID_REGLA_TRIBUTARIA)';
        DBMS_OUTPUT.PUT_LINE('ID_REGLA_TRIBUTARIA agregada.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('ID_REGLA_TRIBUTARIA ya existe. Sin cambios.');
    END IF;
END;
