PROMPT 5. Cargando parametros de facturas especiales...
-- Serie y correlativos: el correlativo se bloquea con FOR UPDATE al asignar un
-- numero, por lo que no hay duplicados ni huecos. La serie es editable.
MERGE INTO CXP_PARAMETRO P
USING (
    SELECT 'CXP_FACTURA_ESPECIAL' GRUPO_PARAMETRO, 'SERIE' CODIGO,
           'Serie de facturas especiales' NOMBRE, 'FESP' VALOR_TEXTO,
           CAST(NULL AS NUMBER) VALOR_NUMERO FROM DUAL
    UNION ALL
    SELECT 'CXP_FACTURA_ESPECIAL', 'CORRELATIVO_FACTURA',
           'Ultimo numero de factura especial asignado', NULL, 0 FROM DUAL
    UNION ALL
    SELECT 'CXP_FACTURA_ESPECIAL', 'CORRELATIVO_CONSTANCIA',
           'Ultimo numero de constancia emitido', NULL, 0 FROM DUAL
) S
ON (P.GRUPO_PARAMETRO = S.GRUPO_PARAMETRO AND P.CODIGO = S.CODIGO)
WHEN NOT MATCHED THEN
    INSERT (GRUPO_PARAMETRO, CODIGO, NOMBRE, VALOR_TEXTO, VALOR_NUMERO, ACTIVO)
    VALUES (S.GRUPO_PARAMETRO, S.CODIGO, S.NOMBRE, S.VALOR_TEXTO, S.VALOR_NUMERO, 'S');

-- Aprobadores autorizados: se registran desde Configuracion > Parametros con
--   GRUPO_PARAMETRO = 'CXP_FE_APROBADOR', CODIGO = 'USUARIO_<id>',
--   VALOR_NUMERO = USU_ID_USUARIO, VALOR_TEXTO = ROL_ID_ROL con el que aprueba, ACTIVO = 'S'.
-- No se precargan usuarios: deben existir en la tabla comun USUARIO.

COMMIT;

