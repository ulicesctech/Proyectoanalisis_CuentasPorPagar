PROMPT 4. Creando CXP_FACTURA_ESPECIAL...
DECLARE
    V_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_N FROM USER_TABLES WHERE TABLE_NAME = 'CXP_FACTURA_ESPECIAL';
    IF V_N > 0 THEN
        DBMS_OUTPUT.PUT_LINE('CXP_FACTURA_ESPECIAL ya existe. Sin cambios.');
        RETURN;
    END IF;
    EXECUTE IMMEDIATE q'[
        CREATE TABLE CXP_FACTURA_ESPECIAL (
            ID_FACTURA_ESPECIAL   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            ID_DOCUMENTO          NUMBER         NOT NULL,
            PROVEEDOR_NOMBRE      VARCHAR2(200)  NOT NULL,
            PROVEEDOR_NIT         VARCHAR2(20),
            PROVEEDOR_CUI         VARCHAR2(20),
            PROVEEDOR_DIRECCION   VARCHAR2(300),
            DESCRIPCION_OPERACION VARCHAR2(1000) NOT NULL,
            REVISADO_POR          NUMBER,
            FECHA_REVISION        TIMESTAMP,
            OBSERVACION_REVISION  VARCHAR2(1000),
            ESTADO_EMISION        VARCHAR2(20)   DEFAULT 'PENDIENTE' NOT NULL,
            NUMERO_CONSTANCIA     VARCHAR2(40),
            FECHA_EMISION         TIMESTAMP,
            EMITIDO_POR           NUMBER,
            HASH_CONSTANCIA       VARCHAR2(64),
            CREADO_POR            NUMBER         NOT NULL,
            FECHA_CREACION        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_CXP_FACTURA_ESP PRIMARY KEY (ID_FACTURA_ESPECIAL),
            CONSTRAINT UK_CXP_FESP_DOC UNIQUE (ID_DOCUMENTO),
            CONSTRAINT UK_CXP_FESP_CONST UNIQUE (NUMERO_CONSTANCIA),
            CONSTRAINT FK_CXP_FESP_DOC FOREIGN KEY (ID_DOCUMENTO)
                REFERENCES CXP_DOCUMENTO (ID_DOCUMENTO),
            CONSTRAINT FK_CXP_FESP_REV FOREIGN KEY (REVISADO_POR)
                REFERENCES USUARIO (USU_ID_USUARIO),
            CONSTRAINT FK_CXP_FESP_EMI FOREIGN KEY (EMITIDO_POR)
                REFERENCES USUARIO (USU_ID_USUARIO),
            CONSTRAINT FK_CXP_FESP_CREA FOREIGN KEY (CREADO_POR)
                REFERENCES USUARIO (USU_ID_USUARIO),
            CONSTRAINT CK_CXP_FESP_ID_FISCAL CHECK (PROVEEDOR_NIT IS NOT NULL OR PROVEEDOR_CUI IS NOT NULL),
            CONSTRAINT CK_CXP_FESP_ESTADO CHECK (ESTADO_EMISION IN ('PENDIENTE', 'EMITIDA', 'ANULADA')),
            -- Una constancia emitida siempre tiene numero, fecha, emisor y codigo de respaldo.
            CONSTRAINT CK_CXP_FESP_EMISION CHECK (
                (ESTADO_EMISION = 'PENDIENTE' AND NUMERO_CONSTANCIA IS NULL AND FECHA_EMISION IS NULL)
                OR (ESTADO_EMISION = 'EMITIDA' AND NUMERO_CONSTANCIA IS NOT NULL AND FECHA_EMISION IS NOT NULL
                    AND EMITIDO_POR IS NOT NULL AND HASH_CONSTANCIA IS NOT NULL)
                OR ESTADO_EMISION = 'ANULADA'
            ),
            CONSTRAINT CK_CXP_FESP_HASH CHECK (HASH_CONSTANCIA IS NULL OR LENGTH(HASH_CONSTANCIA) = 64)
        )]';
    DBMS_OUTPUT.PUT_LINE('CXP_FACTURA_ESPECIAL creada.');
END;
